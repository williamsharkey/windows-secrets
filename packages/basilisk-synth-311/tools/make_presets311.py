#!/usr/bin/env python3
"""BASILISK 16's programs: presets/b16.tsv, then packages/basilisk-synth/library/presets/*.tsv (factory.tsv first),
with presets/overrides311.tsv replacing shared presets in place (3.11 sounds, gain staging).

    make_presets311.py            writes plugin/presets_gen.h (the program list, "Category: Name")

make_library311.py writes the same rows, in the same order, to \\PRESETS.TSV on the library disc (the browser in
Windows), so a program number and a line of the browser are the same sound.
Lines: category <TAB> name <TAB> DNA; '#' starts a comment.
"""
import glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
SHARED = os.path.join(PKG, '..', 'basilisk-synth', 'library', 'presets')


def preset_files():
    shared = sorted(glob.glob(os.path.join(SHARED, '*.tsv')), key=lambda f: (os.path.basename(f) != 'factory.tsv', f))
    return [os.path.join(PKG, 'presets', 'b16.tsv')] + shared


def overrides():
    """presets/overrides311.tsv: 3.11 versions of shared presets, by (category, name)"""
    o = {}
    p = os.path.join(PKG, 'presets', 'overrides311.tsv')
    if os.path.exists(p):
        for line in open(p, encoding='utf-8'):
            line = line.rstrip('\r\n')
            if line.strip() and not line.startswith('#') and line.count('\t') >= 2:
                c, n, d = [x.strip() for x in line.split('\t')[:3]]
                o[(c, n)] = d
    return o


def rows(files=None):
    out, seen, ov = [], set(), overrides()
    for f in files or preset_files():
        for line in open(f, encoding='utf-8'):
            line = line.rstrip('\r\n')
            if not line.strip() or line.startswith('#') or line.count('\t') < 2:
                continue
            c, n, d = [x.strip() for x in line.split('\t')[:3]]
            if (c, n) in seen:
                continue
            seen.add((c, n)); out.append((c, n, ov.get((c, n), d)))
    return out


def main():
    r = rows()
    esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
    with open(os.path.join(PKG, 'plugin', 'presets_gen.h'), 'w', newline='\n') as h:
        h.write('// generated by tools/make_presets311.py from presets/b16.tsv and basilisk-synth/library/presets - do not edit\n#pragma once\n')
        h.write('struct Preset { const char *name, *dna; };\nstatic const Preset kPresets[] = {\n')
        for c, n, d in r:
            h.write('    {"%s: %s", "%s"},\n' % (esc(c), esc(n), esc(d)))
        h.write('};\n')
    print(len(r), 'programs')


if __name__ == '__main__':
    main()
