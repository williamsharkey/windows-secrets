#!/usr/bin/env python3
"""The Song tab's measured tuning (design/SONG-TAB.md 6): packages/basilisk-synth/library/songs/tuning-dna.json
(tools/songrender/make_tuning.py --dna-out: {"<FNV-1a 64 of the exact DNA text, hex>": {"cents": n, ...}}) as
plugin/tuning_gen.h, a sorted table the plugin looks a preset's DNA up in. Cents are the correction to apply."""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'basilisk-synth', 'library', 'songs', 'tuning-dna.json')
out = os.path.join(here, '..', 'plugin', 'tuning_gen.h')
rows = []
if os.path.exists(src):
    for k, v in json.load(open(src, encoding='utf-8')).items():
        c = int(round(v['cents'] if isinstance(v, dict) else v))
        if c: rows.append((int(k, 16), c, (v.get('pack', '') + ':' + v.get('name', '')) if isinstance(v, dict) else ''))
rows.sort()
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// generated by tools/make_tuning311.py from %s: do not edit\n' % os.path.relpath(src, os.path.join(here, '..', '..', '..')).replace('\\', '/'))
    f.write('#pragma once\n#include <cstdint>\nstruct TuningRow { uint64_t dna; int16_t cents; };\n')
    f.write('static const TuningRow kTuning[] = {\n')
    for h, c, n in rows:
        f.write('    {0x%016xull, %d},   // %s\n' % (h, c, n.replace('*/', '')))
    if not rows: f.write('    {0, 0},\n')
    f.write('};\nstatic const unsigned kTuningCount = %d;\n' % len(rows))
print('%d tuned presets -> %s' % (len(rows), out))
