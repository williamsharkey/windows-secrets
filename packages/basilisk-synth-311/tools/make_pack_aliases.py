#!/usr/bin/env python3
# plugin/pack_aliases_gen.h: renamed packs and presets, so old projects and .song files still find them.
# Source: library/packs/<pack>/RENAMES.TSV (category TAB old name TAB new name), one pack per entry below.
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
PACKS = os.path.join(HERE, '..', '..', 'basilisk-synth', 'library', 'packs')
RENAMED = [('paulywaulophone', 'waulophone', 'PAULYWAULO', 'WAULOPHONE'), ('paulyw', 'waulophone', 'PAULYWAULO', 'WAULOPHONE')]   # old id, new id, old label, new label
def c(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['// generated by tools/make_pack_aliases.py: do not edit', '#pragma once', '',
       'struct PackIdAlias { const char *oldId, *newId, *oldLabel, *newLabel; };',
       'static const PackIdAlias kPackIdAlias[] = {']
out += ['    {%s, %s, %s, %s},' % tuple(map(c, r)) for r in RENAMED]
out += ['};', 'struct PresetAlias { const char *pack, *category, *oldName, *newName; };', 'static const PresetAlias kPresetAlias[] = {']
for new in sorted(set(r[1] for r in RENAMED)):
    for l in open(os.path.join(PACKS, new, 'RENAMES.TSV'), encoding='utf-8'):
        l = l.rstrip('\r\n')
        if not l or l.startswith('#'): continue
        cat, old, nw = l.split('\t')
        out.append('    {%s, %s, %s, %s},' % (c(new), c(cat), c(old), c(nw)))
out += ['};', '']
open(os.path.join(HERE, '..', 'plugin', 'pack_aliases_gen.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
