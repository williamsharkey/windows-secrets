#!/usr/bin/env python3
"""Generate mt/guest/mtsynth.c: the multitimbral experiment's guest, SYNTH.EXE's sound engine without its GUI.
Sound Recorder is driven by the very same code as SYNTH.EXE (the line ranges below are copied from guest/synth.c,
so a lane builds and plays exactly as a normal instance does); the lane layer, the launcher and the host link are new.
  make_mtsynth.py  (writes mt/guest/mtsynth.c)"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, '..', '..', 'guest', 'synth.c')).read().split('\n')
def L(a, b): return '\n'.join(src[a - 1:b])
def find(pat, start=1):
    for i in range(start - 1, len(src)):
        if re.match(pat, src[i]): return i + 1
    raise KeyError(pat)
def func(name):   # a top-level function from its first line to its closing brace at column 0
    a = find(r'^(static |long |int |void |BOOL ).*\b%s\((?!.*\);)' % re.escape(name))
    b = a
    while src[b - 1] != '}': b += 1
    return L(a, b)
o = []
o.append(open(os.path.join(HERE, '..', 'guest', 'mtsynth_head.c')).read())
o.append(L(find(r'^#define NSND'), find(r'^static int sound_lookup') + 4))
o.append(L(find(r'^typedef struct \{ char op;'), find(r'^static int getint') + 9))
o.append(func('macro_repeats'))
parse = func('dna_parse')
parse = parse.replace('left = NR,', 'left = laneRecs,').replace('s0 < NR;', 's0 < laneRecs;').replace('s0 + run < NR', 's0 + run < laneRecs').replace('f + c < NR', 'f + c < laneRecs')
o.append(parse)
for f in ('press',): o.append(func(f))
o.append(L(find(r'^static void menu\(int r'), find(r'^static void menu\(int r')))
for f in ('field_cs',): o.append(func(f))
o.append(L(find(r'^static int length_cs'), find(r'^static int length_cs')))
for f in ('is_playing', 'drop_file', 'seek_pct', 'seek_frac', 'seek_ms', 'pump', 'op_label', 'op_name', 'run_steps'):
    t = func(f)
    if f == 'is_playing': t = t.replace('static BOOL is_playing(int r)', 'static BOOL is_playing_text(int r)')
    t = t.replace('GetScrollRange(sb, SB_CTL, &lo, &hi);', 'if (sb) GetScrollRange(sb, SB_CTL, &lo, &hi); else { lo = 0; hi = 10000; }   /* (mt: a stripped recorder has no bar; its range is always 0..10000) */')
    o.append(t)
o.append(L(find(r'^static void stop_rec\(int r, DWORD id, int fade_ms\);'), find(r'^static void stop_rec\(int r, DWORD id, int fade_ms\);')))
o.append(L(find(r'^static int modArg'), find(r'^static int modArg')))
o.append(func('signature'))
notes = L(find(r'^static BOOL regated'), find(r'^static void rate_rec') + 7)
notes = notes.replace('int L = layer >= 0 && layer < NL ? layer : rlayer[r];\n        if (from > 0 && L >= 0 && L < NL && layerFrames[L] > 0) seek_frac(r, from, layerFrames[L]);',
                      'int L = layer >= 0 && layer < NL ? layer : rlayer[r];\n        if (from > 0 && L >= 0 && L < NL && lnFrames[r / NR][L] > 0) seek_frac(r, from, lnFrames[r / NR][L]);')
notes = notes.replace('layer < 0 ? rlayer[r] : layer, modArg[rr]', 'CARDLAYER(r, layer < 0 ? rlayer[r] : layer), modArg[rr]').replace('bs_arm2(rt[r], id, hz, vol, pan, layer < 0 ? rlayer[r] : layer)', 'bs_arm2(rt[r], id, hz, vol, pan, CARDLAYER(r, layer < 0 ? rlayer[r] : layer))')
notes = notes.replace('L >= 0 && L < NL && layerFrames[L] > 0 && pHz[r]', 'L >= 0 && L < NL && lnFrames[r / NR][L] > 0 && pHz[r]').replace('if (f > layerFrames[L]) f = layerFrames[L];\n                if (f > 0) seek_frac(r, f, layerFrames[L]);', 'if (f > lnFrames[r / NR][L]) f = lnFrames[r / NR][L];\n                if (f > 0) seek_frac(r, f, lnFrames[r / NR][L]);')
notes = notes.replace('    if (t3 - t0 > 30) logf_', '    slowMax = t3 - t0 > slowMax ? t3 - t0 : slowMax; nPlays++;\n    if (t3 - t0 > 30) logf_')
assert 'layerFrames' not in notes, 'unpatched layerFrames'
o.append(notes)
o.append(func('read_lines_now'))
o.append(L(find(r'^#define NPK'), find(r'^static int pk_find')))
pk = func('lib_packs_index').replace(' if (curTab == 6) lib_discs();', '')
o.append(pk)
o.append(func('lib_packs').replace('    if (curTab == 6) lib_discs();\n', ''))
o.append(open(os.path.join(HERE, '..', 'guest', 'mtsynth_tail.c')).read())
open(os.path.join(HERE, '..', 'guest', 'mtsynth.c'), 'w').write(
    '/* GENERATED by mt/tools/make_mtsynth.py from mtsynth_head.c, guest/synth.c and mtsynth_tail.c: do not edit. */\n' + '\n\n'.join(o) + '\n')
print('mtsynth.c written')
