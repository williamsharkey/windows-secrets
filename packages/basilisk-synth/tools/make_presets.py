#!/usr/bin/env python3
"""library/presets/*.tsv -> plugin/presets_gen.h (the programs, "Category: Name") and PRESETS.TSV for the library disc.

    make_presets.py [OUT_PRESETS_TSV]
Lines: category <TAB> name <TAB> DNA; '#' starts a comment. Factory presets first, then the other files by name.
"""
import glob, os, re, sys
PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = sorted(glob.glob(os.path.join(PKG, 'library', 'presets', '*.tsv')), key=lambda f: (os.path.basename(f) != 'factory.tsv', f))
rows = []
for f in files:
    for line in open(f, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'):
            continue
        c, n, d = line.split('\t')[:3]
        rows.append((c.strip(), n.strip(), d.strip()))
esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
with open(os.path.join(PKG, 'plugin', 'presets_gen.h'), 'w') as h:
    h.write('// generated by tools/make_presets.py from library/presets/*.tsv - do not edit\n#pragma once\n')
    h.write('static const struct { const char *name, *dna; } kPresets[] = {\n')
    for c, n, d in rows:
        h.write('    {"%s: %s", "%s"},\n' % (esc(c), esc(n), esc(d)))
    h.write('};\n')
    # the library disc's sound names (tools/make_library.py names them the same way), so DNA naming them parses
    # before the machine is up
    builtin = set(re.findall(r'"([a-z0-9]+)"', open(os.path.join(PKG, 'core', 'dna.cpp')).read().split('kSoundNames', 1)[1].split('};', 1)[0]))
    names = set()
    for f in glob.glob(os.path.join(PKG, 'library', 'sources', '*', '*.wav')):
        n = re.sub(r'_+', '_', re.sub(r'[^a-z0-9_]', '_', os.path.splitext(os.path.basename(f))[0].lower().replace('#', 's'))).strip('_')
        if n and n not in builtin:
            names.add(n)
    h.write('static const char *const kLibraryNames[] = {\n')
    for n in sorted(names):
        h.write('    "%s",\n' % n)
    h.write('    nullptr};\n')
def edition(dna):
    """DNA.md 2.4: 'xp' when the DNA uses any file only XP has, else 'w31' (library sounds do not count)"""
    shared31, both = {'chimes', 'chord', 'ding', 'tada'}, {'ringin', 'ringout'}
    xp = set(builtin) | {'chimesxp', 'chordxp', 'dingxp', 'tadaxp'}
    names = []
    for layer in dna.split(';')[0].split('/'):
        m = re.match(r'[a-z0-9_]+', layer)
        if m: names.append(m.group(0))
        names += re.findall(r'[IM]([a-z0-9_]+)', layer)
    return 'xp' if any(n in xp and n not in shared31 and n not in both for n in names) else 'w31'
if len(sys.argv) > 1:
    # PRESETS.TSV for the disc: category, name, DNA, edition (the guest's [All] [W3.11] [XP] filters)
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\r\n') as t:
        for c, n, d in rows:
            t.write('%s\t%s\t%s\t%s\n' % (c, n, d, edition(d)))
print(len(rows), 'presets')
